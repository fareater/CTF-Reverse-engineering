#!/usr/bin/env python3
idx = [0x07,0x02,0x0f,0x00,0x0b,0x13,0x05,0x0d,0x08,0x01,0x11,0x04,0x0a,0x10,0x03,0x0e,0x06,0x12,0x09,0x0c]
dat = [0x41,0xbe,0x40,0x14,0xe6,0xa1,0xb3,0xd0,0xcd,0x16,0x3c,0x01,0xb1,0xcb,0xb2,0xed,0x4c,0x52,0x31,0x4b]

lcg = (-0x5a6f11e4) & 0xffffffff
key = [0x00] * 20

for i in range(20):
    lcg = (lcg * 0x19660d + 0x3c6ef35f) & 0xffffffff
    k = (dat[i] ^ (lcg >> 16)) - (i * 11 + 5)
    key[idx[i]] = k & 0xff

checksum1 = sum((i + 3) * key[i] for i in range(20)) % 997
assert checksum1 == 83, f"checksum1 = {checksum1}, ожидалось 83"
assert max(key) <= 35, f"байт > 35: {max(key)}"

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
chars = "".join(ALPHABET[k] for k in key)
groups = [chars[i:i+5] for i in range(0, 20, 5)]
license_key = "LIC-" + "-".join(groups)

print(license_key)
